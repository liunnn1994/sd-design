import assert from 'node:assert/strict';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
const directory = resolve(root, 'packages/web-vue/components/model-selector/assets/logos');
const target = resolve(root, 'packages/web-react/src/model-selector/logo-sources.ts');
const sources = Object.fromEntries(
  readdirSync(directory)
    .filter((file) => file.endsWith('.svg'))
    .sort()
    .map((file) => [
      file.slice(0, -4),
      `data:image/svg+xml;base64,${readFileSync(resolve(directory, file)).toString('base64')}`,
    ]),
);
assert.ok(sources.default, 'The provider logo fallback is required');
const output = `// Generated by scripts/generate-react-model-selector-logos.ts. Do not edit.\nexport const modelSelectorLogoSources: Readonly<Record<string, string>> = ${JSON.stringify(sources, null, 2)};\n`;
if (process.argv.includes('--check'))
  assert.deepEqual(
    (await import(pathToFileURL(target).href)).modelSelectorLogoSources,
    sources,
    'Run scripts/generate-react-model-selector-logos.ts to synchronize provider logos',
  );
else writeFileSync(target, output);
