import type { Config, XastElement } from 'svgo';

import { execFileSync } from 'node:child_process';
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { optimize } from 'svgo';

import type { IconNode } from '../../web-core/src/icon/types.ts';
import type { IconCategory } from './gen-icons.ts';

const header = '// Generated by web-vue/scripts/gen-icons.ts. Do not edit.\n';
const coreRoot = path.resolve(import.meta.dirname, '../../web-core/src/icon/icons');
const reactRoot = path.resolve(import.meta.dirname, '../../web-react/src/icon');

function serialize(node: XastElement): IconNode {
  return {
    tag: node.name,
    attributes: node.attributes,
    children: node.children.flatMap((child): (IconNode | string)[] => {
      if (child.type === 'element') return [serialize(child)];
      if (child.type === 'text' || child.type === 'cdata') return [child.value];
      return [];
    }),
  };
}

async function removeStale(root: string, expected: Set<string>) {
  for (const name of await readdir(root)) {
    if (!/^icon-[\w-]+\.ts$/.test(name) || expected.has(name)) continue;
    const filename = path.join(root, name);
    if ((await readFile(filename, 'utf8')).startsWith(header)) await rm(filename);
  }
}

export async function generateReactIcons(data: IconCategory[], config: Config) {
  await mkdir(coreRoot, { recursive: true });
  await mkdir(reactRoot, { recursive: true });
  const exports: string[] = [];
  const imports: string[] = [];
  const names: string[] = [];
  const catalog: { name: string; componentName: string; category: string; title: string }[] = [];
  const expected = new Set<string>();
  for (const category of data) {
    for (const icon of category.list) {
      let definition: IconNode | undefined;
      optimize(await readFile(icon.path, 'utf8'), {
        ...config,
        path: icon.path,
        plugins: [
          ...(config.plugins ?? []).filter(
            (plugin) => typeof plugin === 'string' || plugin.name !== 'addAttributesToSVGElement',
          ),
          {
            name: 'captureIconDefinition',
            fn(root) {
              const svg = root.children.find(
                (node): node is XastElement => node.type === 'element' && node.name === 'svg',
              );
              if (svg) definition = serialize(svg);
              return {};
            },
          },
        ],
      });
      if (!definition) throw new Error(`Missing SVG root: ${icon.path}`);
      const filename = `${icon.name}.ts`;
      expected.add(filename);
      await writeFile(
        path.join(coreRoot, filename),
        `${header}import type { IconNode } from '../types.js';\nconst definition: IconNode = ${JSON.stringify(definition)};\nexport default definition;\n`,
      );
      await writeFile(
        path.join(reactRoot, filename),
        `${header}import definition from '@sdata/web-core/icon/icons/${icon.name}';\nimport { createIcon } from './create-icon.js';\nexport const ${icon.componentName} = createIcon('${icon.name.slice(5)}', '${icon.componentName}', definition);\nexport default ${icon.componentName};\n`,
      );
      exports.push(`export { default as ${icon.componentName} } from './${icon.name}.js';`);
      imports.push(`import ${icon.componentName} from './${icon.name}.js';`);
      names.push(icon.componentName);
      catalog.push({
        name: icon.name,
        componentName: icon.componentName,
        category: category.type,
        title: category.title,
      });
    }
  }
  await removeStale(coreRoot, expected);
  await removeStale(reactRoot, expected);
  await writeFile(
    path.join(coreRoot, 'catalog.ts'),
    `${header}export const iconCatalog = ${JSON.stringify(catalog)} as const;\n`,
  );
  await writeFile(
    path.join(reactRoot, 'index.ts'),
    `${header}${exports.join('\n')}\nexport { default } from './sd-react-icon.js';\nexport type { GeneratedIconProps, GeneratedIconInstance } from './create-icon.js';\nexport { iconCatalog } from '@sdata/web-core/icon/icons/catalog';\n`,
  );
  await writeFile(
    path.join(reactRoot, 'sd-react-icon.ts'),
    `${header}${imports.join('\n')}\nexport default { ${names.join(', ')} };\n`,
  );
  execFileSync(
    process.execPath,
    [fileURLToPath(new URL('../bin/oxfmt', import.meta.resolve('oxfmt'))), coreRoot, reactRoot],
    { cwd: path.resolve(import.meta.dirname, '../../..') },
  );
}
